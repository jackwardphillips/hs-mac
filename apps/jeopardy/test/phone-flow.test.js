import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { Game } from '../src/game.js';

test('server authorizes phone flow and automatically opens buzzers', () => {
  const game = new Game('1234', { rounds: [[{name:'Test',clues:[{prompt:'one two three',response:'Paris',value:200},{prompt:'Next',response:'Other',value:400}]}]], final:{} });
  const a = game.addPlayer(), b = game.addPlayer();
  const client = () => ({readyState:1, OPEN:1, send(){broadcasts++;}});
  const host = client(), phoneA = client(), phoneB = client();
  const sockets = new Map([[host,{code:'1234',role:'host'}],[phoneA,{code:'1234',role:'player',playerId:a.id}],[phoneB,{code:'1234',role:'player',playerId:b.id}]]);
  let scheduled, delay, broadcasts = 0;
  const context = vm.createContext({games:new Map([['1234',game]]),sockets, clearTimeout(){}, setTimeout:(callback,ms) => {scheduled=callback;delay=ms;return {unref(){}};} });
  const source = fs.readFileSync(new URL('../src/server.js',import.meta.url),'utf8');
  vm.runInContext(source.slice(source.indexOf('function handle('),source.indexOf('\nserver.listen(')),context);
  const send = (client,type,extra={}) => context.handle(client,{type,...extra});
  assert.throws(() => send(phoneA,'start'), /host/);
  assert.throws(() => send(host,'start'), /draw/);
  send(phoneA,'signature',{strokes:[[[0,0],[1,1]]]});
  send(phoneB,'signature',{strokes:[[[0,1],[1,0]]]});
  send(host,'start');
  const picker = game.picker === a.id ? phoneA : phoneB;
  const other = picker === phoneA ? phoneB : phoneA;
  assert.throws(() => send(other,'select',{category:0,clue:0}), /pick/);
  assert.throws(() => send(host,'select',{category:0,clue:0}), /pick/);
  send(picker,'select',{category:0,clue:0});
  assert.equal(game.phase,'clue'); assert.ok(delay > 1400 && delay <= 1500);
  assert.throws(() => send(host,'openBuzzers'), /Unknown/);
  game.opensAt = Date.now(); scheduled(); assert.equal(game.phase,'buzzing');
  send(phoneA,'buzz');
  const count = broadcasts; send(phoneB,'buzz'); assert.equal(broadcasts,count);
  send(phoneA,'response',{response:'paris'});
  assert.equal(game.attempt.suggested,true);
  assert.throws(() => send(phoneA,'judge',{correct:true}), /host/);
  assert.throws(() => send(phoneA,'override',{correct:false}), /host/);
  assert.equal(a.score,200);
  assert.equal(game.phase,'result');
  game.resultEndsAt = Date.now(); scheduled();
  assert.equal(a.score,200); assert.equal(game.picker,a.id);
  assert.equal(game.phase,'board'); scheduled(); assert.equal(game.phase,'board');
});
